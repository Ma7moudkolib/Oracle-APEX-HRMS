-- DELETE_EMPLOYEE_ACCOUNT
create or replace PROCEDURE DELETE_EMPLOYEE_ACCOUNT (
    P_EMPLOYEE_ID IN USERS.EMPLOYEE_ID%TYPE
)
IS
BEGIN
    DELETE FROM USERS
    WHERE EMPLOYEE_ID = P_EMPLOYEE_ID;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20001,
            'No account found for this employee.'
        );
    END IF;
END DELETE_EMPLOYEE_ACCOUNT;
