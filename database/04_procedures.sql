-- ADD_USER
create or replace PROCEDURE ADD_USER (
    P_USERNAME IN VARCHAR2,
    P_EMAIL IN VARCHAR2,
    P_PASSWORD IN VARCHAR2,
    P_EMPLOYEE_ID IN NUMBER
)
IS
BEGIN
    INSERT INTO USERS (
        USERNAME,
        EMAIL,
        PASSWORD,
        EMPLOYEE_ID
    )
    VALUES (
        P_USERNAME,
        P_EMAIL,
        P_PASSWORD,
        P_EMPLOYEE_ID
    );
END ADD_USER;
