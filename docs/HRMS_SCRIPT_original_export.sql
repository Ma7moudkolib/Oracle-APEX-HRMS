    p_payroll_run_id OUT NUMBER
)
AS
    l_month          DATE;
    l_created_by     NUMBER;
    l_count           NUMBER;
    l_invalid         NUMBER;
    l_working_days    NUMBER;
BEGIN
    IF p_payroll_month IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'Please select a payroll month.');
    END IF;

    l_month := TRUNC(p_payroll_month, 'MM');

    SELECT employee_id
      INTO l_created_by
      FROM employees
     WHERE LOWER(email) = LOWER(p_app_user);

    SELECT COUNT(*)
      INTO l_count
      FROM payroll_runs
     WHERE payroll_month = l_month;

    IF l_count > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20002, 'A payroll run already exists for this month.'
        );
    END IF;

    SELECT COUNT(*)
      INTO l_count
      FROM payroll
     WHERE payroll_month >= l_month
       AND payroll_month < ADD_MONTHS(l_month, 1);

    IF l_count > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20003,
            'Payroll records already exist for this month.'
        );
    END IF;

    SELECT COUNT(*)
      INTO l_invalid
      FROM employees
     WHERE status = 'ACTIVE'
       AND (salary IS NULL OR salary < 0);

    IF l_invalid > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20004,
            'Some active employees have an invalid salary.'
        );
    END IF;

    SELECT COUNT(*)
      INTO l_working_days
      FROM (
          SELECT l_month + LEVEL - 1 AS work_date
            FROM dual
          CONNECT BY LEVEL <=
              ADD_MONTHS(l_month, 1) - l_month
      )
     WHERE IS_WORKING_DAY(work_date) = 1;

    IF l_working_days = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20008, 'No working days found for the selected month.'
        );
    END IF;

    INSERT INTO payroll_runs (
        payroll_month,
        status,
        created_by
    )
    VALUES (
        l_month,
        'DRAFT',
        l_created_by
    )
    RETURNING payroll_run_id INTO p_payroll_run_id;

    INSERT INTO payroll (
        employee_id,
        payroll_month,
        basic_salary,
        allowances,
        deductions,
        net_salary,
        status,
        payroll_run_id
    )
    SELECT
        e.employee_id,
        l_month,
        e.salary,
        0,
        LEAST(
            e.salary,
            ROUND(
                (e.salary / l_working_days) *
                (
                    NVL(a.absent_days, 0) +
                    (NVL(a.late_days, 0) * 0.25)
                ),
                2
            )
        ),
        e.salary - LEAST(
            e.salary,
            ROUND(
                (e.salary / l_working_days) *
                (
                    NVL(a.absent_days, 0) +
                    (NVL(a.late_days, 0) * 0.25)
                ),
                2
            )
        ),
        'PENDING',
        p_payroll_run_id
    FROM employees e
    LEFT JOIN (
        SELECT
            employee_id,
            SUM(CASE WHEN status = 'ABSENT' THEN 1 ELSE 0 END)
                AS absent_days,
            SUM(CASE WHEN status = 'LATE' THEN 1 ELSE 0 END)
                AS late_days
        FROM attendance
        WHERE attendance_date >= l_month
          AND attendance_date < ADD_MONTHS(l_month, 1)
        GROUP BY employee_id
    ) a
      ON a.employee_id = e.employee_id
    WHERE e.status = 'ACTIVE';

    l_count := SQL%ROWCOUNT;

    IF l_count = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20005, 'No active employees were found.'
        );
    END IF;

    UPDATE payroll_runs
       SET status = 'CALCULATED'
     WHERE payroll_run_id = p_payroll_run_id;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(
            -20006,
            'The logged-in APEX account is not linked to an employee record.'
        );

    WHEN TOO_MANY_ROWS THEN
        RAISE_APPLICATION_ERROR(
            -20007,
            'The logged-in account matches multiple employee records.'
        );
END GENERATE_PAYROLL_RUN;
