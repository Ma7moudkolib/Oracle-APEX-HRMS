    P_USERNAME IN VARCHAR2,
    P_PASSWORD IN VARCHAR2
)
RETURN BOOLEAN
IS
    L_STORED_PASSWORD USERS.PASSWORD%TYPE;
    L_IS_ACTIVE       USERS.IS_ACTIVE%TYPE;
