create or replace FUNCTION HASH_PASSWORD (
    P_PASSWORD IN VARCHAR2
)
RETURN VARCHAR2
IS
    L_HASH VARCHAR2(64);
BEGIN
    IF P_PASSWORD IS NULL THEN
        RETURN NULL;
    END IF;

    EXECUTE IMMEDIATE
        'SELECT LOWER(STANDARD_HASH(:p_password, ''SHA256'')) FROM dual'
        INTO L_HASH
        USING P_PASSWORD;

    RETURN L_HASH;
END HASH_PASSWORD;
